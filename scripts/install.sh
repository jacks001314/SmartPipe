#!/usr/bin/env bash
# SmartPipe Linux installer.
# Docker mode installs the four services through deploy/docker-compose.yml.
# Binary mode installs a build.sh bundle and the units in deploy/systemd.
set -euo pipefail

SOURCE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
MODE="docker"
INSTALL_DIR="/opt/smartpipe"
ENV_FILE=""
BUNDLE_DIR=""
DSN="${SMARTPIPE_DSN:-}"
LANXIN_APP_ID="${LANXIN_APP_ID:-}"
LANXIN_APP_SECRET="${LANXIN_APP_SECRET:-}"
LANXIN_API_BASE="${LANXIN_API_BASE:-https://open.e.lanxin.cn/open/apigw}"
APPSERVER_ADDR="${SMARTPIPE_APPSERVER_ADDR:-}"
APPSERVER_TOKEN="${SMARTPIPE_APPSERVER_TOKEN:-}"
DO_BUILD=1
INSTALL_DOCKER=0
START_SERVICES=1

usage() {
  cat <<'EOF'
Usage: sudo scripts/install.sh [options]
  --mode docker|binary      Deployment mode (default docker)
  --install-dir DIR         Install directory (default /opt/smartpipe)
  --env-file FILE           Existing environment file containing real secrets
  --bundle DIR              build.sh output directory (required by binary mode)
  --dsn DSN                 Generate .env when none exists
  --lanxin-app-id ID        Lanxin robot app id for generated .env
  --lanxin-app-secret KEY   Lanxin robot secret for generated .env
  --lanxin-api-base URL     Lanxin API gateway
  --appserver-addr URL      Optional default Syntropy App Server
  --appserver-token TOKEN   Optional App Server session token
  --install-docker          Install Docker with get.docker.com when missing
  --skip-build              Reuse smartpipe:local instead of rebuilding the image
  --no-start                Install files but do not start services
EOF
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --mode) MODE="${2:?missing mode}"; shift 2 ;;
    --install-dir) INSTALL_DIR="${2:?missing install dir}"; shift 2 ;;
    --env-file) ENV_FILE="${2:?missing env file}"; shift 2 ;;
    --bundle) BUNDLE_DIR="${2:?missing bundle dir}"; shift 2 ;;
    --dsn) DSN="${2:?missing dsn}"; shift 2 ;;
    --lanxin-app-id) LANXIN_APP_ID="${2:?missing app id}"; shift 2 ;;
    --lanxin-app-secret) LANXIN_APP_SECRET="${2:?missing app secret}"; shift 2 ;;
    --lanxin-api-base) LANXIN_API_BASE="${2:?missing api base}"; shift 2 ;;
    --appserver-addr) APPSERVER_ADDR="${2:?missing app server address}"; shift 2 ;;
    --appserver-token) APPSERVER_TOKEN="${2:?missing app server token}"; shift 2 ;;
    --install-docker) INSTALL_DOCKER=1; shift ;;
    --skip-build) DO_BUILD=0; shift ;;
    --no-start) START_SERVICES=0; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "unknown option: $1" >&2; usage >&2; exit 2 ;;
  esac
done

if [[ "$(id -u)" -ne 0 ]]; then
  echo "install.sh must run as root (use sudo)." >&2
  exit 1
fi
if [[ "$MODE" != "docker" && "$MODE" != "binary" ]]; then
  echo "--mode must be docker or binary" >&2
  exit 2
fi
if [[ -n "$ENV_FILE" && ! -f "$ENV_FILE" ]]; then
  echo "environment file not found: $ENV_FILE" >&2
  exit 2
fi

INSTALL_DIR="$(realpath -m "$INSTALL_DIR")"
case "$INSTALL_DIR" in
  /|/usr|/etc|/var|/opt) echo "refusing unsafe install directory: $INSTALL_DIR" >&2; exit 2 ;;
esac

quote_env() {
  local value
  value="$(printf '%s' "$1" | sed "s/'/'\\\\''/g")"
  printf "'%s'" "$value"
}

random_hex() {
  openssl rand -hex 32
}

random_key() {
  openssl rand -base64 32 | tr -d '\n'
}

generate_env() {
  local output="$1"
  if [[ -z "$DSN" || -z "$LANXIN_APP_ID" || -z "$LANXIN_APP_SECRET" ]]; then
    cat >&2 <<'EOF'
No environment file exists. Provide --env-file, or provide all of:
  --dsn, --lanxin-app-id, --lanxin-app-secret
The installer will generate random service tokens and the AES master key.
EOF
    exit 2
  fi
  local admin_token bridge_token verify_token release_token bot_token crash_token hook_secret master_key commit
  admin_token="$(random_hex)"
  bridge_token="$(random_hex)"
  verify_token="$(random_hex)"
  release_token="$(random_hex)"
  bot_token="$(random_hex)"
  crash_token="$(random_hex)"
  hook_secret="$(random_hex)"
  master_key="$(random_key)"
  commit="$(git -C "$SOURCE_DIR" rev-parse --short=12 HEAD 2>/dev/null || echo unknown)"

  umask 077
  cat > "$output" <<EOF
# Generated by SmartPipe install.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
SMARTPIPE_DSN=$(quote_env "$DSN")
SMARTPIPE_MASTER_KEY=$(quote_env "$master_key")
SMARTPIPE_ADMIN_TOKEN=$(quote_env "$admin_token")
SMARTPIPE_BRIDGE_TOKEN=$(quote_env "$bridge_token")
SMARTPIPE_VERIFY_TOKEN=$(quote_env "$verify_token")
SMARTPIPE_RELEASE_TOKEN=$(quote_env "$release_token")
SMARTPIPE_BOT_INTERNAL_TOKEN=$(quote_env "$bot_token")
SMARTPIPE_CRASH_TOKEN=$(quote_env "$crash_token")
GITHUB_WEBHOOK_SECRET=$(quote_env "$hook_secret")

INTERNAL_TOKEN=$(quote_env "$bot_token")
BRIDGE_TOKEN=$(quote_env "$bridge_token")
CRASH_INGEST_TOKEN=$(quote_env "$crash_token")

LANXIN_APP_ID=$(quote_env "$LANXIN_APP_ID")
LANXIN_APP_SECRET=$(quote_env "$LANXIN_APP_SECRET")
LANXIN_API_BASE=$(quote_env "$LANXIN_API_BASE")
BOT_REQUIRE_AT_ME=true

SMARTPIPE_VERSION=0.1.0
SMARTPIPE_COMMIT=$(quote_env "$commit")
SMARTPIPE_BIND_ADDR=0.0.0.0
SMARTPIPE_ADMIN_PORT=8092
SMARTPIPE_BRIDGE_PORT=8090
SMARTPIPE_BOT_PORT=8093
SMARTPIPE_VERIFY_PORT=8095
SMARTPIPE_ADMIN_ADDR=:8092
SMARTPIPE_BRIDGE_ADDR=:8090
SMARTPIPE_VERIFY_ADDR=:8095
SMARTPIPE_MCP_ADDR=:8097
BOT_HTTP_ADDR=:8093
SMARTPIPE_APPSERVER_ADDR=$(quote_env "$APPSERVER_ADDR")
SMARTPIPE_APPSERVER_TOKEN=$(quote_env "$APPSERVER_TOKEN")
SMARTPIPE_RELEASE_SCHEDULE=off
SMARTPIPE_CRASH_RETENTION_DAYS=30
SMARTPIPE_CRASH_REJECT_RETENTION_DAYS=7
SMARTPIPE_CRASH_RETENTION_HOURS=6
SMARTPIPE_VERIFY_CONCURRENCY=2
SMARTPIPE_VERIFY_TIMEOUT=30m
CRASH_PROJECT_ID=
SMARTPIPE_CRASH_PROJECT=
EOF
  chmod 600 "$output"
  echo "GENERATED $output (secrets are not printed)"
}

copy_tree() {
  if [[ "$(realpath -m "$SOURCE_DIR")" == "$(realpath -m "$INSTALL_DIR")" ]]; then
    return
  fi
  mkdir -p "$INSTALL_DIR"
  local item
  for item in backend sdks web configs scripts docs; do
    if [[ -e "$SOURCE_DIR/$item" ]]; then
      # 先删后拷，避免上一次部署留下的源文件（例如已删除的页面）参与构建。
      rm -rf "$INSTALL_DIR/$item"
      cp -a "$SOURCE_DIR/$item" "$INSTALL_DIR/"
    fi
  done
  for item in Dockerfile .dockerignore smartpipe.yaml README.md; do
    if [[ -e "$SOURCE_DIR/$item" ]]; then
      cp -a "$SOURCE_DIR/$item" "$INSTALL_DIR/"
    fi
  done
  mkdir -p "$INSTALL_DIR/deploy"
  for item in docker-compose.yml .env.example README.md; do
    if [[ -f "$SOURCE_DIR/deploy/$item" ]]; then
      cp -a "$SOURCE_DIR/deploy/$item" "$INSTALL_DIR/deploy/"
    fi
  done
  for item in systemd postgres; do
    if [[ -d "$SOURCE_DIR/deploy/$item" ]]; then
      cp -a "$SOURCE_DIR/deploy/$item" "$INSTALL_DIR/deploy/"
    fi
  done
  find "$INSTALL_DIR/scripts" -maxdepth 1 -type f -name '*.sh' -exec chmod 0755 {} +
}

source_env() {
  for candidate in "$SOURCE_DIR/deploy/.env" "$INSTALL_DIR/deploy/.env"; do
    if [[ -f "$candidate" ]]; then
      echo "$candidate"
      return 0
    fi
  done
  return 1
}

install_docker_if_requested() {
  if command -v docker >/dev/null 2>&1 && docker compose version >/dev/null 2>&1; then
    return
  fi
  if [[ "$INSTALL_DOCKER" -ne 1 ]]; then
    echo "Docker Engine with the Compose plugin is required; rerun with --install-docker." >&2
    exit 1
  fi
  if ! command -v curl >/dev/null 2>&1; then
    echo "curl is required to install Docker" >&2
    exit 1
  fi
  local tmp
  tmp="$(mktemp)"
  curl -fsSL https://get.docker.com -o "$tmp"
  sh "$tmp"
  rm -f "$tmp"
  systemctl enable --now docker
}

wait_compose_healthy() {
  local dir="$1" i service cid state ok services
  for i in $(seq 1 60); do
    ok=1
    services="$(cd "$dir" && docker compose config --services 2>/dev/null || true)"
    for service in $services; do
      cid="$(cd "$dir" && docker compose ps -q "$service" 2>/dev/null || true)"
      if [[ -z "$cid" ]]; then ok=0; break; fi
      state="$(docker inspect --format '{{if .State.Health}}{{.State.Health.Status}}{{else}}{{.State.Status}}{{end}}' "$cid" 2>/dev/null || echo unknown)"
      if [[ "$state" != "healthy" && "$state" != "running" ]]; then ok=0; break; fi
    done
    if [[ "$ok" -eq 1 ]]; then
      echo "ALL SERVICES HEALTHY"
      (cd "$dir" && docker compose ps)
      return 0
    fi
    sleep 2
  done
  (cd "$dir" && docker compose ps) >&2 || true
  (cd "$dir" && docker compose logs --tail=80) >&2 || true
  echo "services did not become healthy within 120 seconds" >&2
  return 1
}

install_docker_mode() {
  install_docker_if_requested
  docker info >/dev/null
  docker compose version >/dev/null

  local env_path="$INSTALL_DIR/deploy/.env"
  mkdir -p "$INSTALL_DIR/deploy/data/verify" "$INSTALL_DIR/deploy/data/workspaces" \
    "$INSTALL_DIR/deploy/data/releases" "$INSTALL_DIR/deploy/data/go" \
    "$INSTALL_DIR/deploy/data/go-cache" "$INSTALL_DIR/deploy/data/npm"
  chown -R 10001:10001 "$INSTALL_DIR/deploy/data"

  if [[ -n "$ENV_FILE" ]]; then
    install -m 600 "$ENV_FILE" "$env_path"
  elif [[ ! -f "$env_path" ]]; then
    if ! generated_from="$(source_env)"; then
      generate_env "$env_path"
    elif [[ "$generated_from" != "$env_path" ]]; then
      install -m 600 "$generated_from" "$env_path"
    fi
  fi
  chmod 600 "$env_path"
  (cd "$INSTALL_DIR/deploy" && docker compose config -q)

  if [[ "$DO_BUILD" -eq 1 ]]; then
    (cd "$INSTALL_DIR/deploy" && docker compose build)
  fi
  if [[ "$START_SERVICES" -eq 1 ]]; then
    (cd "$INSTALL_DIR/deploy" && docker compose up -d --remove-orphans)
    wait_compose_healthy "$INSTALL_DIR/deploy"
  fi
  echo "DOCKER INSTALL OK: $INSTALL_DIR"
  echo "Admin UI: http://<host>:8092/healthz"
}

install_binary_mode() {
  local bundle="${BUNDLE_DIR:-$SOURCE_DIR/dist}"
  bundle="$(realpath -m "$bundle")"
  if [[ ! -f "$bundle/bin/admin-api" || ! -f "$bundle/web/index.html" ]]; then
    echo "binary bundle is incomplete: $bundle" >&2
    echo "Run scripts/build.sh --os linux first, then pass --bundle." >&2
    exit 2
  fi

  if ! getent group smartpipe >/dev/null 2>&1; then groupadd --system smartpipe; fi
  if ! id smartpipe >/dev/null 2>&1; then
    useradd --system --uid 10001 --gid smartpipe --home-dir /var/lib/smartpipe --shell /usr/sbin/nologin smartpipe
  fi

  install -d -m 0755 "$INSTALL_DIR/bin" "$INSTALL_DIR/web" "$INSTALL_DIR/configs"
  for file in "$bundle"/bin/*; do install -m 0755 "$file" "$INSTALL_DIR/bin/"; done
  rm -rf -- "$INSTALL_DIR/web"
  cp -a "$bundle/web" "$INSTALL_DIR/web"
  if [[ -d "$bundle/configs" ]]; then cp -a "$bundle/configs/." "$INSTALL_DIR/configs/"; fi

  install -d -m 0750 -o smartpipe -g smartpipe \
    /var/lib/smartpipe/verify /var/lib/smartpipe/workspaces /var/lib/smartpipe/releases \
    /var/lib/smartpipe/go /var/lib/smartpipe/go-cache /var/lib/smartpipe/npm
  install -d -m 0750 /etc/smartpipe

  local env_path=/etc/smartpipe/smartpipe.env
  if [[ -n "$ENV_FILE" ]]; then
    install -m 600 "$ENV_FILE" "$env_path"
  elif [[ ! -f "$env_path" ]]; then
    generate_env "$env_path"
  fi

  local unit source
  for unit in smartpipe-patch-verifier smartpipe-admin-api smartpipe-bridge smartpipe-bot smartpipe-scheduler; do
    source="$INSTALL_DIR/deploy/systemd/$unit.service"
    if [[ ! -f "$source" ]]; then
      echo "systemd unit missing: $source" >&2
      exit 1
    fi
    sed -e "s|@INSTALL_DIR@|$INSTALL_DIR|g" -e "s|@STATE_DIR@|/var/lib/smartpipe|g" \
      "$source" > "/etc/systemd/system/$unit.service"
  done
  systemctl daemon-reload
  if [[ "$START_SERVICES" -eq 1 ]]; then
    systemctl enable --now smartpipe-patch-verifier.service smartpipe-admin-api.service \
      smartpipe-bridge.service smartpipe-bot.service smartpipe-scheduler.service
    local i port ok
    for i in $(seq 1 60); do
      ok=1
      for port in 8092 8090 8095 8093 8098; do
        if ! curl -fsS --max-time 3 "http://127.0.0.1:$port/healthz" >/dev/null 2>&1; then ok=0; fi
      done
      if [[ "$ok" -eq 1 ]]; then
        echo "ALL SERVICES HEALTHY"
        break
      fi
      sleep 2
    done
    if [[ "$ok" -ne 1 ]]; then
      echo "services did not become healthy within 120 seconds" >&2
      systemctl --no-pager --full status smartpipe-patch-verifier.service \
        smartpipe-admin-api.service smartpipe-bridge.service smartpipe-bot.service \
        smartpipe-scheduler.service >&2 || true
      journalctl --no-pager -n 120 -u smartpipe-patch-verifier.service \
        -u smartpipe-admin-api.service -u smartpipe-bridge.service -u smartpipe-bot.service >&2 || true
      exit 1
    fi
  fi
  echo "BINARY INSTALL OK: $INSTALL_DIR"
}

copy_tree
case "$MODE" in
  docker) install_docker_mode ;;
  binary) install_binary_mode ;;
esac
